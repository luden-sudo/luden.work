import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const code=ts.transpileModule(fs.readFileSync('src/lib/day-plan.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ESNext}}).outputText;
const {blocksFor,planState,planImpact,validDay}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const routine=JSON.parse(fs.readFileSync('scripts/day-seed.json','utf8')).map((b,i)=>({...b,id:String(i)}));
const original=JSON.stringify(routine);
const plan={id:'plan',title:'Amigos',description:'Un café',time:'17:00',end_time:'18:45',plan_date:'2026-10-06',weekdays:[2],kind:'descanso',remind:false};
const blocks=[...routine,plan];
const adjusted=blocksFor(blocks,plan.plan_date);
assert.equal(adjusted.find(b=>b.title==='Trabajo').end_time,'17:00');
assert.ok(!adjusted.some(b=>b.title==='Merienda y descanso'||b.title==='Ducha'));
assert.equal(adjusted.find(b=>b.time==='18:45').title,'Descansar');
assert.equal(adjusted.find(b=>b.title==='Cena').time,'21:00');
assert.equal(adjusted.find(b=>b.title==='Dormir').time,'23:45');
assert.deepEqual(blocksFor(blocks,'2026-10-07'),blocksFor(routine,'2026-10-07'));
assert.deepEqual(blocksFor(blocks.filter(b=>b.id!==plan.id),plan.plan_date),blocksFor(routine,plan.plan_date));
assert.equal(JSON.stringify(routine),original);
assert.equal(planImpact(routine,plan).length,3);
const split={...plan,time:'16:30',end_time:'17:00'};
const splitDay=blocksFor([...routine,split],plan.plan_date).filter(b=>b.title==='Trabajo');
assert.equal(splitDay.length,2);assert.equal(splitDay[0].end_time,'16:30');assert.equal(splitDay[1].time,'17:00');assert.equal(splitDay[1].resumed,true);
assert.equal(planState(blocks,new Date('2026-10-06T15:00:00Z')).current.id,'plan');
assert.equal(planState(blocks,new Date('2026-10-06T16:45:00Z')).current.title,'Descansar');
const weekend={...plan,plan_date:'2026-10-10',weekdays:[6]};
assert.equal(blocksFor([...routine,weekend],'2026-10-10').length,1);
assert.equal(planState([...routine,weekend],new Date('2026-10-10T14:00:00Z')).current,null);
const during=planState([...routine,weekend],new Date('2026-10-10T15:30:00Z'));
assert.equal(during.current.id,'plan');assert.equal(during.remaining,75);
assert.equal(planState([...routine,weekend],new Date('2026-10-10T16:45:00Z')).current,null);
assert.equal(blocksFor([...routine,weekend],'2026-10-17').length,0);
assert.equal(validDay('2026-02-30'),false);assert.equal(validDay('2026-10-06'),true);
const two=blocksFor([...routine,split,{...plan,id:'second',time:'17:15',end_time:'17:30'}],plan.plan_date);
assert.equal(two.filter(b=>b.title==='Trabajo').length,3);
assert.equal(new Set(two.map(b=>b.id+':'+b.time)).size,two.length);
console.log('PASS: plan interruption, partial resumption, multiple plans, no recurrence changes, cancel restoration, weekends, clock transitions and invalid dates.');
const earlyPlan={...plan,time:'05:00',end_time:'05:30'};
const resumedNight=planState([...routine,earlyPlan],new Date('2026-10-06T04:00:00Z'));
assert.equal(resumedNight.current.title,'Dormir');
assert.equal(resumedNight.remaining,60);
assert.equal(resumedNight.current.resumed,true);
assert.equal(planState([...routine,earlyPlan],new Date('2026-10-06T05:00:00Z')).current.title,'Levantarse');
console.log('PASS: sleeping resumes after an early plan and stops at wake-up time.');
