import fs from 'node:fs';
import assert from 'node:assert/strict';
import {plan,adjustments} from './day-modules.mjs';
const blocks=JSON.parse(fs.readFileSync('scripts/day-seed.json','utf8')).map((block,i)=>({...block,id:String(i)}));
const {dayRows,schoolChanges,changedRows,adjustmentError}=adjustments;
const day='2026-10-06',original=JSON.stringify(blocks);
assert.equal(adjustmentError(blocks,day,[]),'');
assert.equal(adjustmentError(blocks.map(block=>({...block,end_time:null})),day,[]),'');
const rows=schoolChanges(blocks,day,dayRows(blocks,day),'late','11:45',true);
const overrides=changedRows(blocks,day,rows),changes=[{day,overrides,updated_at:'test'}];
assert.equal(adjustmentError(blocks,day,overrides),'');
const list=plan.blocksFor(blocks,day,changes);
assert.equal(list.find(block=>block.title==='Levantarse').time,'10:30');
assert.equal(list.find(block=>/prepararse/.test(block.title)).time,'11:00');
assert.equal(list.find(block=>/salir de casa/i.test(block.title)).time,'11:20');
const school=list.find(block=>block.kind==='estudio');
assert.equal(school.time,'11:45');assert.equal(school.end_time,'14:45');
assert.equal(plan.planState(blocks,new Date(day+'T07:00:00Z'),changes).current.title,'Dormir');
assert.equal(plan.planState(blocks,new Date(day+'T09:50:00Z'),changes).current.id,school.id);
assert.deepEqual(plan.blocksFor(blocks,'2026-10-07',changes),plan.blocksFor(blocks,'2026-10-07'));
assert.deepEqual(plan.blocksFor(blocks,day,[]),plan.blocksFor(blocks,day));
const noClass=changedRows(blocks,day,schoolChanges(blocks,day,dayRows(blocks,day),'no-class','',false));
const free=plan.blocksFor(blocks,day,[{day,overrides:noClass,updated_at:''}]);
assert.ok(!free.some(block=>block.kind==='estudio'||/salir de casa|volver a casa/i.test(block.title)));
assert.equal(plan.planState(blocks,new Date(day+'T09:00:00Z'),[{day,overrides:noClass,updated_at:''}]).current,null);
assert.ok(adjustmentError(blocks,day,[{...overrides.find(row=>row.block_id===school.id),time:'15:30'}]));
assert.ok(adjustmentError(blocks,day,[{...overrides[0],time:'99:99'}]));
assert.ok(adjustmentError(blocks,day,[overrides[0],overrides[0]]));
const outing={id:'plan',title:'Cena fuera',description:'',time:'20:30',end_time:'22:00',plan_date:day,weekdays:[],kind:'comida',remind:true};
const adapted=plan.blocksFor([...blocks,outing],day,changes);
assert.equal(adapted.find(block=>block.id==='plan').time,'20:30');
assert.equal(adapted.find(block=>block.title==='Dormir').time,'23:45');
assert.equal(JSON.stringify(blocks),original);
console.log('PASS: late school + morning, fixed school end, no class + free time, restoration, other days, validation, plans and weekly routine preserved.');
